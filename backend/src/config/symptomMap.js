/**
 * Маппинг симптомов на специализации врачей.
 * Чтобы добавить новый симптом — просто добавьте строку.
 * Названия специализаций должны точно совпадать с полем doctors.specialization в БД.
 */
const SYMPTOM_TO_SPECS = {
  'Головная боль':        ['Невролог', 'Терапевт'],
  'Боль в горле':         ['Терапевт'],
  'Температура':          ['Терапевт'],
  'Кашель':               ['Терапевт'],
  'Боль в животе':        ['Хирург', 'Терапевт'],
  'Боль в спине':         ['Невролог', 'Хирург'],
  'Проблемы со зрением':  ['Офтальмолог'],
  'Проблемы с кожей':     ['Дерматолог'],
  'Боль в суставах':      ['Невролог', 'Хирург'],
  'Усталость':            ['Терапевт', 'Кардиолог'],
  'Тошнота':              ['Хирург', 'Терапевт'],
  'Сердцебиение':         ['Кардиолог', 'Терапевт'],
}

/**
 * Принимает массив названий симптомов,
 * возвращает уникальный массив специализаций (объединение).
 */
function getSpecsForSymptoms(symptomNames) {
  const specs = new Set()
  for (const name of symptomNames) {
    const matched = SYMPTOM_TO_SPECS[name] ?? []
    matched.forEach(s => specs.add(s))
  }
  return [...specs]
}

module.exports = { SYMPTOM_TO_SPECS, getSpecsForSymptoms }
